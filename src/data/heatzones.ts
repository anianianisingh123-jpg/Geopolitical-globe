/**
 * Build a GeoJSON polygon from lat-first points: swaps to [lng, lat], closes
 * the ring, and forces clockwise winding. The globe renderer follows the d3
 * spherical convention (same as world-atlas), where a counter-clockwise
 * exterior ring means "everything except this shape".
 */
function poly(points: LatLng[]): Polygon {
  const ring = points.map(([lat, lng]) => [lng, lat]);
  let twiceArea = 0;
  for (let i = 0; i < ring.length; i++) {
    const [x1 = 0, y1 = 0] = ring[i] ?? [];
    const [x2 = 0, y2 = 0] = ring[(i + 1) % ring.length] ?? [];
    twiceArea += x1 * y2 - x2 * y1;
  }
  if (twiceArea > 0) ring.reverse();
  const first = ring[0];
  if (first) ring.push([...first]);
  return { type: "Polygon", coordinates: [ring] };
}

